import { build as viteBuild } from "vite";
import { build as bundle } from "esbuild";
import {
  mkdir,
  readdir,
  readFile,
  writeFile,
  copyFile,
  rm,
} from "node:fs/promises";
import { resolve, dirname, basename, extname, relative } from "node:path";
import { fingerprint } from "./source-hashes.mjs";
const root = process.cwd(),
  dist = resolve(root, "dist"),
  client = resolve(root, ".runtime/client");
if (dirname(dist) !== root || basename(dist) !== "dist")
  throw new Error("Refusing to clean outside the project build directory.");
await rm(dist, { recursive: true, force: true });
await viteBuild();
await mkdir(resolve(client, "docs"), { recursive: true });
for (const name of ["README.md", "BUILD_NOTES.md", "VALIDATION.md"]) {
  await copyFile(name, resolve(client, "docs", name));
}
await mkdir(resolve(client, "validation"), { recursive: true });
for (const file of await readdir("docs/validation")) {
  if (file.endsWith(".json"))
    await copyFile(
      resolve("docs/validation", file),
      resolve(client, "validation", file),
    );
}
const types = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".svg": "image/svg+xml",
  ".woff2": "font/woff2",
  ".md": "text/markdown; charset=utf-8",
  ".json": "application/json; charset=utf-8",
};
const assets = {};
async function collect(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = resolve(directory, entry.name);
    if (entry.isDirectory()) await collect(path);
    else if (types[extname(path)])
      assets[`/${relative(client, path).replaceAll("\\", "/")}`] = {
        type: types[extname(path)],
        body: (await readFile(path)).toString("base64"),
      };
  }
}
await collect(client);
const metadata = { sourceFingerprint: await fingerprint() };
await writeFile(
  "worker/assets.generated.ts",
  `// Generated by scripts/build.mjs.\nexport const assets:Record<string,{type:string;body:string}>=${JSON.stringify(assets)};\nexport const metadata=${JSON.stringify(metadata)};\n`,
);
await mkdir(resolve(dist, "server"), { recursive: true });
await bundle({
  entryPoints: ["worker/index.ts"],
  outfile: "dist/server/index.js",
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  minify: true,
  legalComments: "none",
});
await mkdir(resolve(dist, ".openai"), { recursive: true });
await copyFile(".openai/hosting.json", "dist/.openai/hosting.json");
console.log(
  `Built ${Object.keys(assets).length} embedded assets. Source fingerprint ${metadata.sourceFingerprint}.`,
);
await import("./validate-artifact.mjs");
